#ifndef DS35M1GB_H
#define DS35M1GB_H
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
/* Datasheet rev07 Table3.1: OTP_PRT7, OTP_EN6, ECC_EN4, QE0.
 * Other B0 bits are reserved and have no guaranteed restorable readback. */
#define DS35_B0_DEFINED_MASK 0xd1u
#define DS35_MAX_CLOCK_HZ    83000000u
#define DS35_PAGE            2048u
#define DS35_OOB             128u
#define DS35_PAGES_PER_BLOCK 64u
#define DS35_BLOCKS          1024u
#define DS35_TAG_OFFSET      4u
#define DS35_TAG_CAPACITY    60u
/* Full main data + user spare only; ECC parity is generated by NAND. */
#define DS35_PROGRAM_BYTES (DS35_PAGE + 64u)

enum ds35_result
{
    DS35_OK        = 0,
    DS35_CORRECTED = 1,
    DS35_EINVAL    = -1,
    DS35_IO        = -2,
    DS35_TIMEOUT   = -3,
    DS35_ECC       = -4,
    DS35_BAD       = -5,
    DS35_READ_ONLY = -6,
    DS35_ID        = -7,
    DS35_NOT_READY = -8
};

struct ds35_bus
{
    void *ctx;
    /* Header bytes are wire order; a complete call asserts then releases CS.
     * Exactly one of tx/rx can be non-NULL. Return 0 or a negative error.
     * Implementations must finish/abort DMA before returning, including failure.
     */
    int (*transfer)(void *, const uint8_t *, size_t, const uint8_t *, uint8_t *, size_t, unsigned);
    void (*delay_us)(void *, uint32_t);
    /* Data width only: all commands/addresses remain x1. */
    unsigned data_width;
    /* true only AFTER E5 A1 and QE/ECC readback; false BEFORE restoring B0.
     * false must select the known serial probe clock, and prohibit quad data;
     * it must NOT change NAND QE or issue a command itself. */
    int (*quad_ready)(void *, bool);
};

/* Shutdown evidence is retained on failure; no fabricated observed value when
 * SET/GET or the clock transition did not complete. Table3.1 defines B0 bits
 * 7,6,4,0; comparison checks those bits, preserving raw bytes as evidence. */
struct ds35_shutdown_diagnostic
{
    const char *phase;
    int         result;
    uint8_t     saved, expected, observed;
    bool        attempted, expected_valid, observed_valid;
};

struct ds35_operation_diagnostic
{
    const char *phase;
    uint32_t    page;
    int         result;
    uint8_t     expected, observed, status, compare_mask;
    bool        expected_valid, observed_valid, status_valid;
};

struct ds35_nand
{
    struct ds35_bus                  bus;
    uint32_t                         first_block, block_count;
    bool                             ready, writable, fault;
    bool                             feature_saved;
    uint8_t                          saved_feature;
    struct ds35_shutdown_diagnostic  shutdown;
    struct ds35_operation_diagnostic operation;
    uint32_t                         corrected_reads, uncorrectable_reads;
    /* One shared-SRAM page bounce buffer, retained until DMA completes. */
    _Alignas(32) uint8_t page[DS35_PAGE + DS35_OOB];
    uint8_t bad[(DS35_BLOCKS + 7u) / 8u];
    uint8_t checked[(DS35_BLOCKS + 7u) / 8u];
};

/* Caller serializes every operation. Probe is non-destructive: no unlock/erase.
 * first=0,count=0 is ID/status-only: EMPTY accessible range; all array reads,
 * programs/erases/BBM and protection unlock remain forbidden. No partition guess.
 * Volatile reset/QE/ECC setup/restoration is necessary even for read-only use. */
int ds35_probe(struct ds35_nand *, const struct ds35_bus *, uint32_t first, uint32_t count);
int ds35_read_status(struct ds35_nand *, uint8_t *status);
int ds35_shutdown(struct ds35_nand *);
int ds35_allow_writes(struct ds35_nand *);
int ds35_read(
    struct ds35_nand *, uint32_t page, void *data, size_t bytes, void *tags, size_t tag_bytes);
#if WATCH_NAND_STARTUP_TESTS
/* TEMP RO cross-check only: full main page via8 separate03/x1 cache reads.
 * Does not change the configured bus width, QE or write authorization. */
int ds35_read_x1_reference(struct ds35_nand *, uint32_t page, void *, size_t);
#endif
int ds35_program(struct ds35_nand *,
    uint32_t    page,
    const void *data,
    size_t      bytes,
    const void *tags,
    size_t      tag_bytes);
int ds35_erase(struct ds35_nand *, uint32_t block);
/* 0 good, DS35_BAD for marked bad, other negative for I/O error. */
int ds35_check_bad(struct ds35_nand *, uint32_t block);
int ds35_mark_bad(struct ds35_nand *, uint32_t block);
int ds35_ecc_status(uint8_t status);
#endif
